function [MeasuredFrequency, PeakMagnitude] = LocalMeasureFFTPeaks( ...
        Frequency, Magnitude, TargetFrequencies, SearchHalfWidth)
%% Measure the strongest Hamming-FFT bin in a nonoverlapping local band.

    Frequency = Frequency(:);
    Magnitude = Magnitude(:);
    TargetFrequencies = TargetFrequencies(:);

    if numel(Frequency) ~= numel(Magnitude)
        error('RunDemoSampler:FFTLengthMismatch', ...
            'FFT frequency and magnitude vectors must have equal lengths.');
    end

    MeasuredFrequency = zeros(size(TargetFrequencies));
    PeakMagnitude = zeros(size(TargetFrequencies));

    for k = 1:numel(TargetFrequencies)
        SearchMask = abs( ...
            Frequency - TargetFrequencies(k)) <= SearchHalfWidth;

        if ~any(SearchMask)
            error('RunDemoSampler:EmptyToneSearchBand', ...
                'No Hamming-FFT bins lie inside a desired-tone search band.');
        end

        CandidateIndices = find(SearchMask);
        [PeakMagnitude(k), LocalPeakIndex] = ...
            max(Magnitude(SearchMask));
        MeasuredFrequency(k) = ...
            Frequency(CandidateIndices(LocalPeakIndex));
    end
end


function AliasFrequency = LocalFoldToFirstNyquist( ...
        InputFrequency, SamplingFrequency)
%% Fold a nonnegative frequency into the real-signal first Nyquist zone.

    AliasFrequency = abs(mod( ...
        InputFrequency + SamplingFrequency / 2, ...
        SamplingFrequency) - SamplingFrequency / 2);
end


function [PSDFrequency, PowerPSD] = LocalHammingPSD( ...
        InputSignal, SamplingFrequency, ...
        WindowLength, OverlapLength, FFTLength)
%% Hamming-Welch PSD with sampler-specific matched-time lengths.

    InputSignal = InputSignal(:);

    if numel(InputSignal) < WindowLength
        error('RunDemoSampler:OutputPSDRecordTooShort', ...
            'The sampler output is shorter than its Welch window.');
    end

    HammingWindow = hamming(WindowLength, "periodic");

    [PowerPSD, PSDFrequency] = pwelch( ...
        InputSignal, ...
        HammingWindow, ...
        OverlapLength, ...
        FFTLength, ...
        SamplingFrequency, ...
        "onesided");
end


function ResultText = LocalPassFail(Condition)
%% Return compact command-window compliance text.

    if Condition
        ResultText = 'PASS';
    else
        ResultText = 'FAIL';
    end
end
