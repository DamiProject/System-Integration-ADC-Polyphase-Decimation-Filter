function [MeasuredFrequency, PeakMagnitude] = LocalMeasureFFTPeaks( ...
        Frequency, Magnitude, TargetFrequencies, SearchHalfWidth)
%% Measure the strongest Hamming-FFT bin in each local search band.

    Frequency = Frequency(:);
    Magnitude = Magnitude(:);
    TargetFrequencies = TargetFrequencies(:);

    if numel(Frequency) ~= numel(Magnitude)
        error('RunDemoQuantizer:FFTLengthMismatch', ...
            'FFT frequency and magnitude vectors must have equal lengths.');
    end

    MeasuredFrequency = zeros(size(TargetFrequencies));
    PeakMagnitude = zeros(size(TargetFrequencies));

    for k = 1:numel(TargetFrequencies)
        SearchMask = abs( ...
            Frequency - TargetFrequencies(k)) <= SearchHalfWidth;

        if ~any(SearchMask)
            error('RunDemoQuantizer:EmptyToneSearchBand', ...
                'No Hamming-FFT bins lie inside a data-tone search band.');
        end

        CandidateIndices = find(SearchMask);
        [PeakMagnitude(k), LocalPeakIndex] = ...
            max(Magnitude(SearchMask));
        MeasuredFrequency(k) = ...
            Frequency(CandidateIndices(LocalPeakIndex));
    end
end


function [PSDFrequency, PowerPSD] = LocalHammingPSD( ...
        InputSignal, SamplingFrequency, ...
        WindowLength, OverlapLength, FFTLength)
%% Hamming-Welch PSD using the sampler-rate analysis lengths.

    InputSignal = InputSignal(:);

    if numel(InputSignal) < WindowLength
        error('RunDemoQuantizer:PSDRecordTooShort', ...
            'The signal is shorter than the Hamming-Welch window.');
    end

    if OverlapLength >= WindowLength
        error('RunDemoQuantizer:InvalidPSDOverlap', ...
            'PSDOverlapLength must be less than PSDWindowLength.');
    end

    if FFTLength < WindowLength
        error('RunDemoQuantizer:InvalidPSDFFTLength', ...
            'PSDFFTLength must be at least PSDWindowLength.');
    end

    HammingWindow = hamming(WindowLength, "periodic");

    [PowerPSD, PSDFrequency] = pwelch( ...
        InputSignal, ...
        HammingWindow, ...
        OverlapLength, ...
        FFTLength, ...
        SamplingFrequency, ...
        "onesided");
end


function Result = LocalPassFail(Condition)
%% Convert a scalar compliance decision to a readable label.

    if Condition
        Result = "PASS";
    else
        Result = "FAIL";
    end
end
