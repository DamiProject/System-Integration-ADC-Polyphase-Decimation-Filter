    zeros(NumMeasuredComponents, 1);

for k = 1:NumMeasuredComponents

    MeasuredFrequency = ...
        ComponentMeasurements.MeasuredFrequency_Hz(k);

    [~, HammingBin] = ...
        min(abs(HammingFreq - MeasuredFrequency));

    HammingMeasuredMagnitudeDB(k) = ...
        20 * log10( ...
            max(HammingMagnitude(HammingBin), ...
                realmin("double")));

    [~, STFTBin] = ...
        min(abs(STFTFreq - MeasuredFrequency));

    STFTPeakAboveNoiseDB(k) = ...
        max(STFTRelativeToNoiseDB(STFTBin, :));

    [~, SummaryPhaseBin] = ...
        min(abs(PhaseFreq - MeasuredFrequency));

    SummaryWrappedPhase(k) = ...
        WrappedPhase(SummaryPhaseBin);
end

