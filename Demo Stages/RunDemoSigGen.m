%% ==========================================
%% AWGN RMS ESTIMATION FROM WELCH PSD
%% ==========================================

NoisePSDMask = ...
    PSDFreq > DCGuardBandwidth & ...
    PSDFreq <= Fs/2 & ...
    ~(PSDFreq >= DesiredBandLower & ...
    PSDFreq <= DesiredBandUpper) & ...
    abs(PSDFreq - DetectedInterferenceFrequency) > 50e6;

% Estimate the white-noise power spectral density directly from PSD bins
% outside DC, the receiver-known desired band, and the blindly detected
% narrowband interference region.
EstimatedAWGNPSD = mean(PSD(NoisePSDMask));

% For a one-sided PSD of a real signal, the white-noise bandwidth extends
% from DC to Nyquist.
NoiseBandwidth = Fs / 2;

EstimatedAWGNPower = ...
    EstimatedAWGNPSD * NoiseBandwidth;

EstimatedAWGNRMS = ...
    sqrt(EstimatedAWGNPower);

fprintf("\nWELCH-PSD BROADBAND-NOISE ESTIMATION\n");
fprintf("Estimated AWGN PSD   : %.6e V^2/Hz\n", ...
    EstimatedAWGNPSD);
fprintf("Estimated AWGN power : %.6e V^2\n", ...
    EstimatedAWGNPower);
fprintf("Estimated AWGN RMS   : %.4f V RMS\n", ...
    EstimatedAWGNRMS);

