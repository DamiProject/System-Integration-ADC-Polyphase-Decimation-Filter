function State = RunDemoDecimator(State, ShowPlots)
%% =======================================================
%% FIXED-POINT POLYPHASE FIR DECIMATOR DEMONSTRATION
%% =======================================================
% Move the ADC encoder's complete signed two's-complement record through
% the floating-point reference and fixed-point polyphase decimators. This
% design stage establishes the coefficient, product, and accumulator
% formats and produces the 2.5 GS/s target-rate digital output. The same
% received record is then used to characterize filter response, alias
% protection, fixed-point error, tone preservation, SNR, and SINR.


    %% ==========================================
    %% VALIDATE INTERSTAGE INPUT CONTRACT
    %% ==========================================

    if nargin < 1 || nargin > 2 || ~isstruct(State)
        error('RunDemoDecimator:InvalidState', ...
            ['RunDemoDecimator requires a State structure input and ', ...
             'an optional logical ShowPlots input.']);
    end

    if nargin < 2 || isempty(ShowPlots)
        ShowPlots = true;
    end

    if ~islogical(ShowPlots) || ~isscalar(ShowPlots)
        error('RunDemoDecimator:InvalidPlotVisibility', ...
            'ShowPlots must be a logical scalar.');
    end

    RequiredStateFields = [ ...
        "Config"; ...
        "Parameters"; ...
        "Fs"; ...
        "Time"; ...
        "InputSignal"; ...
        "CurrentSignal"; ...
        "ADCEncoder"; ...
        "Sampler"; ...
        "SignalGenerator"];

    for k = 1:numel(RequiredStateFields)
        if ~isfield(State, RequiredStateFields(k))
            error('RunDemoDecimator:MissingStateField', ...
                'State.%s is required.', RequiredStateFields(k));
        end
    end

    RequiredEncoderFields = [ ...
        "TwosComplement"; ...
        "DecodedVoltage"; ...
        "InputFormat"; ...
        "LSBWeight_V"; ...
        "SamplingFrequency_Hz"; ...
        "FrameLength"; ...
        "OutputSampleCount"; ...
        "PowerRatios"; ...
        "AnalysisRecord"];

    for k = 1:numel(RequiredEncoderFields)
        if ~isfield(State.ADCEncoder, RequiredEncoderFields(k))
            error('RunDemoDecimator:MissingEncoderField', ...
                'State.ADCEncoder.%s is required.', ...
                RequiredEncoderFields(k));
        end
    end

    RequiredPowerRatioFields = [ ...
        "OutputComponentMeasurements"; ...
        "OutputBroadbandNoisePower_V2"; ...
        "OutputSNR_dB"; ...
        "OutputSINR_dB"];

    for k = 1:numel(RequiredPowerRatioFields)
        if ~isfield( ...
                State.ADCEncoder.PowerRatios, ...
                RequiredPowerRatioFields(k))
            error('RunDemoDecimator:MissingEncoderPowerRatioField', ...
                'State.ADCEncoder.PowerRatios.%s is required.', ...
                RequiredPowerRatioFields(k));
        end
    end

    RequiredAnalysisFields = [ ...
        "InputStartIndex"; ...
        "InputEndIndex"; ...
        "OutputSampleCount"; ...
        "PSDWindowLength"; ...
        "PSDOverlapLength"; ...
        "PSDFFTLength"];

    for k = 1:numel(RequiredAnalysisFields)
        if ~isfield( ...
                State.ADCEncoder.AnalysisRecord, ...
                RequiredAnalysisFields(k))
            error('RunDemoDecimator:MissingEncoderAnalysisField', ...
                'State.ADCEncoder.AnalysisRecord.%s is required.', ...
                RequiredAnalysisFields(k));
        end
    end

    if ~isfield(State.Sampler, "SampleIndex") || ...
            ~isfield(State.Sampler, "Aliasing") || ...
            ~isfield( ...
                State.Sampler.Aliasing, ...
                "PredictedAliasFrequency_Hz")
        error('RunDemoDecimator:MissingSamplerState', ...
            ['The sampler source indices and predicted ADC-rate ', ...
             'interference alias are required.']);
    end

    if ~isfield(State.SignalGenerator, "Measurements") || ...
            ~isfield( ...
                State.SignalGenerator.Measurements, ...
                "DesiredFrequencies_Hz") || ...
            ~isfield( ...
                State.SignalGenerator.Measurements, ...
                "InterferenceFrequency_Hz")
        error('RunDemoDecimator:MissingSignalMeasurements', ...
            ['The two receiver-measured data frequencies and the ', ...
             'measured interference frequency are required.']);
    end

    if ~isprop(State.Config, "DSPParams") || ...
            ~isprop(State.Config, "DecimatorRequirements")
        error('RunDemoDecimator:MissingDesignConfiguration', ...
            ['State.Config must provide DSPParams and ', ...
             'DecimatorRequirements.']);
    end

    DSPP = State.Config.DSPParams;
    Requirements = State.Config.DecimatorRequirements;
    P = State.Parameters;

    InputSamplingFrequency = double(State.Fs);
    InputTime = double(State.Time(:));
    InputCodes = State.CurrentSignal(:);
    EncoderCodes = State.ADCEncoder.TwosComplement(:);
    InputVoltage = double(State.ADCEncoder.DecodedVoltage(:));
    InputFormat = State.ADCEncoder.InputFormat;
    LSBWeight = double(State.ADCEncoder.LSBWeight_V);
    InputSourceSampleIndex = ...
        double(State.Sampler.SampleIndex(:));

    validateattributes( ...
        InputSamplingFrequency, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'}, ...
        mfilename, ...
        'State.Fs');

    validateattributes( ...
        LSBWeight, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'}, ...
        mfilename, ...
        'State.ADCEncoder.LSBWeight_V');

    if ~isa(InputCodes, 'int8') || isempty(InputCodes)
        error('RunDemoDecimator:InvalidInputCodes', ...
            ['State.CurrentSignal must be the nonempty signed int8 ', ...
             'two''s-complement stream produced by RunDemoADCEncoder.']);
    end

    NumberInputSamples = numel(InputCodes);

    if numel(InputTime) ~= NumberInputSamples || ...
            numel(InputVoltage) ~= NumberInputSamples || ...
            numel(EncoderCodes) ~= NumberInputSamples || ...
            numel(InputSourceSampleIndex) ~= NumberInputSamples
        error('RunDemoDecimator:StateLengthMismatch', ...
            ['The encoder codes, decoded voltage, input time, and ', ...
             'sampler source-index records must have equal lengths.']);
    end

    HandoffCodesOK = isequal(InputCodes, EncoderCodes);
    HandoffCountOK = NumberInputSamples == ...
        double(State.ADCEncoder.OutputSampleCount);
    VoltageScaleTolerance = max( ...
        1e-12, 32 * eps(max(abs(InputVoltage))));
    HandoffVoltageScaleOK = max(abs( ...
        InputVoltage - double(InputCodes) * LSBWeight)) <= ...
        VoltageScaleTolerance;

    if ~HandoffCodesOK || ~HandoffCountOK || ...
            ~HandoffVoltageScaleOK
        error('RunDemoDecimator:EncoderHandoffMismatch', ...
            ['State.CurrentSignal must be the complete encoder output ', ...
             'with the reported ADC voltage scale.']);
    end


    %% ==========================================
    %% APPROVED DECIMATOR CONFIGURATION
    %% ==========================================

    ConfiguredInputSamplingFrequency = ...
        double(DSPP.getValue("Fs_DSP"));
    DecimationFactor = double(DSPP.getValue("DcF"));
    FrameLength = double(DSPP.getValue("FrameLength"));
    Fpass = double(DSPP.getValue("Fpass"));
    Fstop = double(DSPP.getValue("Fstop"));
    Apass = double(DSPP.getValue("Apass"));
    Astop = double(DSPP.getValue("Astop"));

    validateattributes( ...
        DecimationFactor, ...
        {'numeric'}, ...
        {'scalar', 'integer', 'finite', 'positive'}, ...
        mfilename, ...
        'DcF');
    validateattributes( ...
        FrameLength, ...
        {'numeric'}, ...
        {'scalar', 'integer', 'finite', 'positive'}, ...
        mfilename, ...
        'FrameLength');

    RequiredRequirementFields = [ ...
        "HeadroomBits"; ...
        "MaxCoefficientWordLength"; ...
        "MaxAccumulatorWordLength"; ...
        "MaxGroupDelay_s"; ...
        "MaxDesiredToneLoss_dB"; ...
        "MaxFrequencyErrorBins"; ...
        "MinAliasAttenuation_dB"; ...
        "MinFixedPointErrorSNR_dB"; ...
        "MinMACReductionPercent"; ...
        "MinSNRImprovement_dB"; ...
        "MinSINRImprovement_dB"];

    for k = 1:numel(RequiredRequirementFields)
        if ~isfield(Requirements, RequiredRequirementFields(k))
            error('RunDemoDecimator:MissingRequirement', ...
                'DecimatorRequirements.%s is required.', ...
                RequiredRequirementFields(k));
        end
    end

    HeadroomBits = double(Requirements.HeadroomBits);
    validateattributes( ...
        HeadroomBits, ...
        {'numeric'}, ...
        {'scalar', 'integer', 'finite', 'nonnegative'}, ...
        mfilename, ...
        'DecimatorRequirements.HeadroomBits');

    OutputSamplingFrequency = ...
        InputSamplingFrequency / DecimationFactor;
    OutputNyquistFrequency = OutputSamplingFrequency / 2;

    RateTolerance = max( ...
        1e-3, 32 * eps(ConfiguredInputSamplingFrequency));
    InputRateOK = abs( ...
        InputSamplingFrequency - ...
        ConfiguredInputSamplingFrequency) <= RateTolerance;
    EncoderRateOK = abs( ...
        InputSamplingFrequency - ...
        double(State.ADCEncoder.SamplingFrequency_Hz)) <= ...
        RateTolerance;
    FrameLengthOK = FrameLength == ...
        double(State.ADCEncoder.FrameLength);
    FrequencyPlanOK = ...
        Fpass > 0 && ...
        Fpass < Fstop && ...
        Fstop <= OutputNyquistFrequency && ...
        OutputNyquistFrequency < InputSamplingFrequency / 2;

    if ~InputRateOK || ~EncoderRateOK || ...
            ~FrameLengthOK || ~FrequencyPlanOK
        error('RunDemoDecimator:ConfigurationMismatch', ...
            ['The DSP input rate, frame length, or anti-alias ', ...
             'frequency plan does not match the encoder handoff.']);
    end


    %% ==========================================
    %% FIXED FIR COEFFICIENT DESIGN
    %% ==========================================

    ReferenceDecimator = FixedDSPDecimator(DSPP);

    CoefficientFormat.WL = ReferenceDecimator.CoeffWL;
    CoefficientFormat.IWL = ReferenceDecimator.CoeffIWL;
    CoefficientFormat.FWL = ReferenceDecimator.CoeffFWL;

    FilterLength = numel(ReferenceDecimator.FilterCoefficients);
    GroupDelayInputSamples = (FilterLength - 1) / 2;
    GroupDelaySeconds = ...
        GroupDelayInputSamples / InputSamplingFrequency;

    NumberBranches = size( ...
        ReferenceDecimator.BranchCoefficients, 1);
    LongestBranchLength = size( ...
        ReferenceDecimator.BranchCoefficients, 2);
    RectangularBranchSlots = numel( ...
        ReferenceDecimator.BranchCoefficients);
    BranchTapCounts = LocalBranchTapCounts( ...
        FilterLength, DecimationFactor);

    ImplementedMACsPerInputSample = ...
        RectangularBranchSlots / DecimationFactor;
    MACReductionPercent = 100 * (1 - ...
        ImplementedMACsPerInputSample / FilterLength);


    %% ==========================================
    %% PASS 1: FULL-PRECISION INTEGER REFERENCE
    %% ==========================================

    [ReferenceCodes, ReferenceMACData, ReferenceFrames] = ...
        LocalProcessFixedStream( ...
            ReferenceDecimator, ...
            InputCodes, ...
            FrameLength, ...
            InputFormat, ...
            CoefficientFormat, ...
            []);


    %% ==========================================
    %% SAFE MAC FORMAT SELECTION
    %% ==========================================

    MACFormat = FindMACFormat( ...
        InputFormat, ...
        CoefficientFormat, ...
        ReferenceDecimator.BranchCoefficients, ...
        ReferenceMACData, ...
        HeadroomBits);


    %% ==========================================
    %% PASS 2: BOUNDED FIXED-POINT MAC
    %% ==========================================

    FixedDecimator = FixedDSPDecimator(DSPP);

    SameCoefficientDesignOK = ...
        isequal( ...
            FixedDecimator.FixedFilterCoefficients, ...
            ReferenceDecimator.FixedFilterCoefficients) && ...
        FixedDecimator.CoeffScale == ...
            ReferenceDecimator.CoeffScale;

    if ~SameCoefficientDesignOK
        error('RunDemoDecimator:CoefficientDesignChanged', ...
            ['The reference and bounded fixed-point paths must use ', ...
             'the same represented FIR coefficients.']);
    end

    [OutputCodes, MACData, FixedFrames] = ...
        LocalProcessFixedStream( ...
            FixedDecimator, ...
            InputCodes, ...
            FrameLength, ...
            InputFormat, ...
            CoefficientFormat, ...
            MACFormat);

    [OutputCodeDomainSignal, MACData] = ...
        FixedToRealConverter(OutputCodes, MACData);
    OutputVoltage = ...
        OutputCodeDomainSignal(:) * LSBWeight;

    ReferenceScale = ...
        2^(-ReferenceMACData.ProductFormat.FWL);
    ReferenceFixedVoltage = ...
        double(ReferenceCodes(:)) * ...
        ReferenceScale * LSBWeight;


    %% ==========================================
    %% FLOATING-POINT DESIGN REFERENCE
    %% ==========================================

    FloatingDecimator = DSP(DSPP);
    [FloatingOutput, FloatingFrames] = ...
        LocalProcessFloatingStream( ...
            FloatingDecimator, ...
            InputVoltage, ...
            FrameLength);


    %% ==========================================
    %% TARGET-RATE TIME BASE
    %% ==========================================

    OutputSampleIndex = FixedFrames.OutputSampleIndex;
    OutputInputSampleIndex = ...
        (OutputSampleIndex + 1) * DecimationFactor;
    OutputTime = InputTime(1) + ...
        (OutputInputSampleIndex - 1) / ...
        InputSamplingFrequency;


    %% ==========================================
    %% DESIGN-INTEGRATION CHECKS
    %% ==========================================

    ExpectedOutputSamples = ...
        ceil(NumberInputSamples / DecimationFactor);
    OutputSampleCountOK = ...
        numel(OutputCodes) == ExpectedOutputSamples && ...
        numel(OutputVoltage) == ExpectedOutputSamples && ...
        numel(FloatingOutput) == ExpectedOutputSamples;
    OutputIndexOK = isequal( ...
        OutputSampleIndex, ...
        (0:ExpectedOutputSamples - 1)');
    NoPaddingRequiredOK = ...
        ReferenceFrames.TotalPaddingSamples == 0 && ...
        FixedFrames.TotalPaddingSamples == 0 && ...
        FloatingFrames.TotalPaddingSamples == 0;
    ReferenceAgreementOK = isequal( ...
        OutputCodes(:), ReferenceCodes(:));
    ZeroOverflowOK = ...
        MACData.TotalAccumulatorOverflowCount == 0;
    CoefficientWordLengthOK = ...
        CoefficientFormat.WL <= ...
        double(Requirements.MaxCoefficientWordLength);
    AccumulatorWordLengthOK = ...
        MACFormat.WL <= ...
        double(Requirements.MaxAccumulatorWordLength);
    GroupDelayOK = ...
        GroupDelaySeconds <= ...
        double(Requirements.MaxGroupDelay_s);
    TypeILinearPhaseOK = ...
        mod(FilterLength, 2) == 1 && ...
        max(abs( ...
            ReferenceDecimator.FilterCoefficients(:) - ...
            flipud(ReferenceDecimator.FilterCoefficients(:)))) <= ...
        128 * eps;
    BranchStructureOK = ...
        NumberBranches == DecimationFactor && ...
        sum(BranchTapCounts) == FilterLength;

    OverallDesignOK = ...
        HandoffCodesOK && ...
        HandoffCountOK && ...
        HandoffVoltageScaleOK && ...
        InputRateOK && ...
        EncoderRateOK && ...
        FrameLengthOK && ...
        FrequencyPlanOK && ...
        SameCoefficientDesignOK && ...
        OutputSampleCountOK && ...
        OutputIndexOK && ...
        NoPaddingRequiredOK && ...
        ReferenceAgreementOK && ...
        ZeroOverflowOK && ...
        CoefficientWordLengthOK && ...
        AccumulatorWordLengthOK && ...
        GroupDelayOK && ...
        TypeILinearPhaseOK && ...
        BranchStructureOK;


    %% ==========================================
    %% DESIGN IMPLEMENTATION SUMMARY
    %% ==========================================

    fprintf("\n");
    fprintf("============================================================\n");
    fprintf("FIXED-POINT POLYPHASE FIR DECIMATOR DESIGN SUMMARY\n");
    fprintf("============================================================\n");
    fprintf("Input representation             : signed int8, Q%d.%d\n", ...
        InputFormat.IWL, InputFormat.FWL);
    fprintf("ADC voltage scale                : %.9f V/code\n", ...
        LSBWeight);
    fprintf("Input / output sample rate       : %.6f / %.6f GS/s\n", ...
        InputSamplingFrequency / 1e9, ...
        OutputSamplingFrequency / 1e9);
    fprintf("Decimation factor                : %d\n", ...
        DecimationFactor);
    fprintf("Input / output frame length      : %d / %d samples\n", ...
        FrameLength, FrameLength / DecimationFactor);
    fprintf("Input / output record length     : %d / %d samples\n", ...
        NumberInputSamples, numel(OutputCodes));
    fprintf("Passband / stopband edge         : %.6f / %.6f GHz\n", ...
        Fpass / 1e9, Fstop / 1e9);
    fprintf("Required ripple / attenuation    : %.4f / %.4f dB\n", ...
        Apass, Astop);
    fprintf("Kaiser Type-I FIR length         : %d taps\n", ...
        FilterLength);
    fprintf("Group delay                      : %d samples (%.4f ns)\n", ...
        GroupDelayInputSamples, GroupDelaySeconds * 1e9);
    fprintf("Polyphase branch tap counts      : %s\n", ...
        mat2str(BranchTapCounts));
    fprintf("Longest branch / padded slots    : %d / %d\n", ...
        LongestBranchLength, RectangularBranchSlots - FilterLength);
    fprintf("Implemented MACs per input       : %.3f\n", ...
        ImplementedMACsPerInputSample);
    fprintf("MAC reduction versus direct FIR  : %.3f %%\n", ...
        MACReductionPercent);
    fprintf("Coefficient format               : Q%d.%d (%d bits)\n", ...
        CoefficientFormat.IWL, ...
        CoefficientFormat.FWL, ...
        CoefficientFormat.WL);
    fprintf("Product format                   : Q%d.%d (%d bits)\n", ...
        MACFormat.ProductIWL, ...
        MACFormat.ProductFWL, ...
        MACFormat.ProductWL);
    fprintf("Accumulator format               : Q%d.%d (%d bits)\n", ...
        MACFormat.IWL, MACFormat.FWL, MACFormat.WL);
    fprintf("Headroom / rounding / overflow   : %d bit / %s / %s\n", ...
        HeadroomBits, ...
        MACFormat.RoundingMethod, ...
        MACFormat.OverflowAction);
    fprintf("Accumulator overflow events      : %d\n", ...
        MACData.TotalAccumulatorOverflowCount);
    fprintf("Reference / bounded code match   : %s\n", ...
        LocalPassFail(ReferenceAgreementOK));
    fprintf("Overall decimator design         : %s\n", ...
        LocalPassFail(OverallDesignOK));


    %% ==========================================
    %% FIXED FIR RESPONSE AND ALIAS PROTECTION
    %% ==========================================

    MaximumDesiredToneLoss_dB = ...
        double(Requirements.MaxDesiredToneLoss_dB);
    MaximumFrequencyErrorBins = ...
        double(Requirements.MaxFrequencyErrorBins);
    MinimumAliasAttenuation_dB = ...
        double(Requirements.MinAliasAttenuation_dB);
    MinimumFixedPointErrorSNR_dB = ...
        double(Requirements.MinFixedPointErrorSNR_dB);
    MinimumMACReductionPercent = ...
        double(Requirements.MinMACReductionPercent);
    MinimumSNRImprovement_dB = ...
        double(Requirements.MinSNRImprovement_dB);
    MinimumSINRImprovement_dB = ...
        double(Requirements.MinSINRImprovement_dB);

    PerformanceRequirementValues = [ ...
        MaximumDesiredToneLoss_dB, ...
        MaximumFrequencyErrorBins, ...
        MinimumAliasAttenuation_dB, ...
        MinimumFixedPointErrorSNR_dB, ...
        MinimumMACReductionPercent, ...
        MinimumSNRImprovement_dB, ...
        MinimumSINRImprovement_dB];

    if any(~isfinite(PerformanceRequirementValues)) || ...
            any(PerformanceRequirementValues < 0)
        error('RunDemoDecimator:InvalidPerformanceRequirement', ...
            ['Every decimator performance requirement must be a ', ...
             'finite nonnegative scalar.']);
    end

    FloatingCoefficients = double( ...
        ReferenceDecimator.FilterCoefficients(:));
    FixedCoefficientCodes = double( ...
        ReferenceDecimator.FixedFilterCoefficients(:));
    CoefficientScale = double(ReferenceDecimator.CoeffScale);
    FixedCoefficients = FixedCoefficientCodes / CoefficientScale;
    ResponsePointCount = double(FixedDecimator.NPoint);

    [ResponsePassbandOK, ResponseStopbandOK, ...
        ResponseOverallOK, PassbandRipple_dB, ...
        StopbandAttenuation_dB, TransitionWidth_Hz, ...
        WorstStopbandFrequency_Hz] = ...
        CheckFIRResponse( ...
            FixedCoefficients, DSPP, ResponsePointCount);

    [AliasProtectionOK, StopbandPlacementOK, ...
        AliasResponseOK, CheckedOutputRate_Hz, ...
        CheckedOutputNyquist_Hz, CheckedStopbandEdge_Hz, ...
        AliasBandAttenuation_dB, ...
        WorstAliasFrequency_Hz] = ...
        CheckDecimatorAliasProtection( ...
            FixedCoefficients, DSPP, ResponsePointCount);

    [CoefficientRMSE, MaximumCoefficientError, ...
        MaximumComplexResponseError, ...
        FloatingPassbandRipple_dB, ...
        FixedPassbandRipple_dB, ...
        PassbandRippleChange_dB, ...
        FloatingStopbandAttenuation_dB, ...
        FixedStopbandAttenuation_dB, ...
        StopbandAttenuationChange_dB, ...
        ComparisonPassbandOK, ComparisonStopbandOK, ...
        ComparisonOverallOK] = ...
        CompareFIRResponses( ...
            FloatingCoefficients, ...
            FixedCoefficientCodes, ...
            CoefficientScale, ...
            DSPP, ...
            ResponsePointCount);

    AliasAttenuationRequirementOK = ...
        AliasBandAttenuation_dB >= MinimumAliasAttenuation_dB;


    %% ==========================================
    %% FIXED-POINT AND POLYPHASE CHARACTERIZATION
    %% ==========================================

    PerformanceAnalyzer = DecimatorAnalyzer(DSPP);
    FixedPointMetrics = ...
        PerformanceAnalyzer.CharacterizeFixedPointDesign( ...
            FloatingOutput, ...
            OutputVoltage, ...
            FixedDecimator, ...
            InputFormat, ...
            MACFormat, ...
            MACData);
    ArchitectureMetrics = ...
        PerformanceAnalyzer.CharacterizePolyphaseArchitecture( ...
            FixedDecimator);

    FixedPointErrorSNR_dB = ...
        FixedPointMetrics.OutputError.ErrorSNRdB;
    FixedPointErrorSNROK = ...
        isinf(FixedPointErrorSNR_dB) || ...
        (isfinite(FixedPointErrorSNR_dB) && ...
        FixedPointErrorSNR_dB >= MinimumFixedPointErrorSNR_dB);
    MeasuredMACReductionPercent = ...
        ArchitectureMetrics.Computation.ImplementedMACReductionPercent;
    MACReductionOK = ...
        MeasuredMACReductionPercent >= ...
        MinimumMACReductionPercent;


    %% ==========================================
    %% FULL-RECORD HAMMING-FFT TONE PRESERVATION
    %% ==========================================

    DesiredFrequencies = double( ...
        State.SignalGenerator.Measurements.DesiredFrequencies_Hz(:));
    InputInterferenceAliasFrequency = double( ...
        State.Sampler.Aliasing.PredictedAliasFrequency_Hz);

    if numel(DesiredFrequencies) ~= 2 || ...
            any(~isfinite(DesiredFrequencies)) || ...
            ~isscalar(InputInterferenceAliasFrequency) || ...
            ~isfinite(InputInterferenceAliasFrequency)
        error('RunDemoDecimator:InvalidMeasuredFrequencies', ...
            ['Exactly two finite desired frequencies and one finite ', ...
             'ADC-rate interference alias are required.']);
    end

    DesiredBandBelowOutputNyquistOK = ...
        all(DesiredFrequencies > 0 & ...
        DesiredFrequencies < OutputNyquistFrequency);

    if ~DesiredBandBelowOutputNyquistOK
        error('RunDemoDecimator:DesiredBandAboveOutputNyquist', ...
            ['Both receiver-measured data tones must lie below the ', ...
             'target-rate Nyquist frequency.']);
    end

    OutputAliasFrequency = LocalFoldToFirstNyquist( ...
        InputInterferenceAliasFrequency, ...
        OutputSamplingFrequency);

    InputSpectrum = SpectrumAnalyzer(P, InputSamplingFrequency);
    OutputSpectrum = SpectrumAnalyzer(P, OutputSamplingFrequency);

    [InputFFTFrequency, InputMagnitude] = ...
        InputSpectrum.HammingFFT(InputVoltage);
    [OutputFFTFrequency, OutputMagnitude] = ...
        OutputSpectrum.HammingFFT(OutputVoltage);

    InputTrueFrequencyResolution = ...
        InputSamplingFrequency / NumberInputSamples;
    OutputTrueFrequencyResolution = ...
        OutputSamplingFrequency / numel(OutputVoltage);
    TrueResolutionTolerance = max( ...
        1e-9, 32 * eps(InputTrueFrequencyResolution));
    MatchedTrueResolutionOK = abs( ...
        OutputTrueFrequencyResolution - ...
        InputTrueFrequencyResolution) <= ...
        TrueResolutionTolerance;
    TrueFrequencyResolution = max( ...
        InputTrueFrequencyResolution, ...
        OutputTrueFrequencyResolution);

    FFTGridTolerance = max( ...
        1e-3, 32 * eps(OutputSamplingFrequency));
    InputComparisonFFTMask = ...
        InputFFTFrequency <= ...
        OutputNyquistFrequency + FFTGridTolerance;
    InputComparisonFFTFrequency = ...
        InputFFTFrequency(InputComparisonFFTMask);
    InputComparisonMagnitude = ...
        InputMagnitude(InputComparisonFFTMask);

    OutputComparisonIndices = ...
        (1:DecimationFactor:numel(OutputFFTFrequency))';
    OutputComparisonFFTFrequency = ...
        OutputFFTFrequency(OutputComparisonIndices);
    OutputComparisonMagnitude = ...
        OutputMagnitude(OutputComparisonIndices);

    if numel(InputComparisonFFTFrequency) ~= ...
            numel(OutputComparisonFFTFrequency) || ...
            any(abs( ...
                InputComparisonFFTFrequency - ...
                OutputComparisonFFTFrequency) > ...
                FFTGridTolerance)
        error('RunDemoDecimator:FFTGridMismatch', ...
            ['Input and output Hamming-FFT comparison grids must ', ...
             'match through the target-rate Nyquist frequency.']);
    end

    MinimumToneSeparation = min(diff(sort(DesiredFrequencies)));

    if MinimumToneSeparation <= 0
        error('RunDemoDecimator:UnresolvedDesiredFrequencies', ...
            'The two desired frequencies must be distinct.');
    end

    ToneSearchHalfWidth = 0.4 * MinimumToneSeparation;

    [InputMeasuredToneFrequency, InputMeasuredToneMagnitude] = ...
        LocalMeasureFFTPeaks( ...
            InputComparisonFFTFrequency, ...
            InputComparisonMagnitude, ...
            DesiredFrequencies, ...
            ToneSearchHalfWidth);
    [OutputMeasuredToneFrequency, OutputMeasuredToneMagnitude] = ...
        LocalMeasureFFTPeaks( ...
            OutputComparisonFFTFrequency, ...
            OutputComparisonMagnitude, ...
            DesiredFrequencies, ...
            ToneSearchHalfWidth);

    ToneFrequencyChange_Hz = ...
        OutputMeasuredToneFrequency - ...
        InputMeasuredToneFrequency;
    ToneFrequencyError_Bins = ...
        abs(ToneFrequencyChange_Hz) / ...
        TrueFrequencyResolution;
    InputToneLevel_dBV = 20 * log10(max( ...
        InputMeasuredToneMagnitude, realmin("double")));
    OutputToneLevel_dBV = 20 * log10(max( ...
        OutputMeasuredToneMagnitude, realmin("double")));
    ToneLevelChange_dB = ...
        OutputToneLevel_dBV - InputToneLevel_dBV;
    ToneLoss_dB = max(0, -ToneLevelChange_dB);

    ToneFrequencyPreservationOK = ...
        all(ToneFrequencyError_Bins <= ...
        MaximumFrequencyErrorBins);
    ToneLevelPreservationOK = ...
        all(ToneLoss_dB <= MaximumDesiredToneLoss_dB);

    TonePreservationSummary = table( ...
        ["Data Signal 1"; "Data Signal 2"], ...
        DesiredFrequencies, ...
        InputMeasuredToneFrequency, ...
        OutputMeasuredToneFrequency, ...
        ToneFrequencyChange_Hz, ...
        ToneFrequencyError_Bins, ...
