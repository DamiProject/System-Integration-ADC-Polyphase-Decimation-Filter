            'FrequencyError_Bins', ...
            'BeforeDecimatorLevel_dBV', ...
            'AfterDecimatorLevel_dBV', ...
            'LevelChange_dB', ...
            'ToneLoss_dB'});


    %% ==========================================
    %% MATCHED-TIME HAMMING-WELCH SNR / SINR
    %% ==========================================
    % The ADC-rate and target-rate Welch windows contain the same amount
    % of physical time. The input SNR integrates the complete 0-5 GHz ADC
    % band; the output SNR integrates the complete 0-1.25 GHz target band.
    % Their difference therefore measures the useful noise-band reduction
    % created by the anti-alias FIR and factor-of-four decimation.

    AnalysisStartIndex = double( ...
        State.ADCEncoder.AnalysisRecord.InputStartIndex);
    AnalysisEndIndex = double( ...
        State.ADCEncoder.AnalysisRecord.InputEndIndex);

    if ~isscalar(AnalysisStartIndex) || ...
            ~isscalar(AnalysisEndIndex) || ...
            AnalysisStartIndex < 1 || ...
            AnalysisStartIndex ~= fix(AnalysisStartIndex) || ...
            AnalysisEndIndex ~= fix(AnalysisEndIndex) || ...
            AnalysisEndIndex < AnalysisStartIndex
        error('RunDemoDecimator:InvalidAnalysisRecord', ...
            'The ADC-encoder analysis-record indices are invalid.');
    end

    InputAnalysisMask = ...
        InputSourceSampleIndex >= AnalysisStartIndex - 1 & ...
        InputSourceSampleIndex <= AnalysisEndIndex - 1;
    InputAnalysisRecord = InputVoltage(InputAnalysisMask);

    if numel(InputAnalysisRecord) ~= double( ...
            State.ADCEncoder.AnalysisRecord.OutputSampleCount)
        error('RunDemoDecimator:EncoderAnalysisRecordMismatch', ...
            ['The reconstructed decimator-input analysis record must ', ...
             'match the ADC encoder measurement record.']);
    end

    if any(OutputInputSampleIndex < 1) || ...
            any(OutputInputSampleIndex > NumberInputSamples) || ...
            any(OutputInputSampleIndex ~= fix(OutputInputSampleIndex))
        error('RunDemoDecimator:InvalidOutputSourceIndex', ...
            'A target-rate sample maps outside the ADC input record.');
    end

    OutputSourceSampleIndex = ...
        InputSourceSampleIndex(OutputInputSampleIndex);
    OutputAnalysisMask = ...
        OutputSourceSampleIndex >= AnalysisStartIndex - 1 & ...
        OutputSourceSampleIndex <= AnalysisEndIndex - 1;
    OutputAnalysisRecord = OutputVoltage(OutputAnalysisMask);

    InputPSDWindowLength = double( ...
        State.ADCEncoder.AnalysisRecord.PSDWindowLength);
    InputPSDOverlapLength = double( ...
        State.ADCEncoder.AnalysisRecord.PSDOverlapLength);
    InputPSDFFTLength = double( ...
        State.ADCEncoder.AnalysisRecord.PSDFFTLength);

    InputPSDLengths = [ ...
        InputPSDWindowLength, ...
        InputPSDOverlapLength, ...
        InputPSDFFTLength];

    if any(mod(InputPSDLengths, DecimationFactor) ~= 0)
        error('RunDemoDecimator:UnmatchedPSDConfiguration', ...
            ['The ADC-rate Welch window, overlap, and FFT lengths ', ...
             'must be divisible by the decimation factor.']);
    end

    OutputPSDWindowLength = ...
        InputPSDWindowLength / DecimationFactor;
    OutputPSDOverlapLength = ...
        InputPSDOverlapLength / DecimationFactor;
    OutputPSDFFTLength = ...
        InputPSDFFTLength / DecimationFactor;

    if numel(InputAnalysisRecord) < InputPSDWindowLength || ...
            numel(OutputAnalysisRecord) < OutputPSDWindowLength
        error('RunDemoDecimator:AnalysisRecordTooShort', ...
            ['The matched input/output analysis records must each ', ...
             'contain one complete Welch window.']);
    end

    [InputPSDFrequency, InputPowerPSD] = ...
        LocalHammingPSD( ...
            InputAnalysisRecord, ...
            InputSamplingFrequency, ...
            InputPSDWindowLength, ...
            InputPSDOverlapLength, ...
            InputPSDFFTLength);
    [OutputPSDFrequency, OutputPowerPSD] = ...
        LocalHammingPSD( ...
            OutputAnalysisRecord, ...
            OutputSamplingFrequency, ...
            OutputPSDWindowLength, ...
            OutputPSDOverlapLength, ...
            OutputPSDFFTLength);

    InputCommonPSDMask = ...
        InputPSDFrequency <= ...
        OutputNyquistFrequency + FFTGridTolerance;
    InputCommonPSDFrequency = ...
        InputPSDFrequency(InputCommonPSDMask);

    if numel(InputCommonPSDFrequency) ~= ...
            numel(OutputPSDFrequency) || ...
            any(abs( ...
                InputCommonPSDFrequency - ...
                OutputPSDFrequency) > FFTGridTolerance)
        error('RunDemoDecimator:PSDGridMismatch', ...
            ['Matched-time input and output Welch PSD grids must ', ...
             'agree through the target-rate Nyquist frequency.']);
    end

    InputComponentFrequencies = [ ...
        DesiredFrequencies; ...
        InputInterferenceAliasFrequency];
    OutputComponentFrequencies = [ ...
        DesiredFrequencies; ...
        OutputAliasFrequency];
    InputComponentNames = [ ...
        "Data Signal 1"; ...
        "Data Signal 2"; ...
        "ADC-Rate Interference Alias"];
    OutputComponentNames = [ ...
        "Data Signal 1"; ...
        "Data Signal 2"; ...
        "Target-Rate Interference Alias"];

    InputComponentMeasurements = ...
        InputSpectrum.MeasureComponentPowerAmplitude( ...
            InputPowerPSD, ...
            InputPSDFrequency, ...
            InputPSDWindowLength, ...
            InputComponentFrequencies, ...
            InputComponentNames);
    OutputComponentMeasurements = ...
        OutputSpectrum.MeasureComponentPowerAmplitude( ...
            OutputPowerPSD, ...
            OutputPSDFrequency, ...
            OutputPSDWindowLength, ...
            OutputComponentFrequencies, ...
            OutputComponentNames);

    InputPSDSpacing = ...
        InputPSDFrequency(2) - InputPSDFrequency(1);
    OutputPSDSpacing = ...
        OutputPSDFrequency(2) - OutputPSDFrequency(1);
    PSDSpacingTolerance = max( ...
        1e-9, 32 * eps(InputPSDSpacing));

    if abs(InputPSDSpacing - OutputPSDSpacing) > ...
            PSDSpacingTolerance
        error('RunDemoDecimator:PSDSpacingMismatch', ...
            ['Matched-time input and output Welch analyses must have ', ...
             'the same frequency-bin spacing.']);
    end

    DesiredBandLower = min(DesiredFrequencies) - 50e6;
    DesiredBandUpper = max(DesiredFrequencies) + 50e6;
    AliasGuardHalfWidth = 50e6;
    DCGuardBandwidth = ...
        2 * InputSamplingFrequency / InputPSDWindowLength;

    InputBroadbandNoiseMask = ...
        InputPSDFrequency > DCGuardBandwidth & ...
        ~(InputPSDFrequency >= DesiredBandLower & ...
        InputPSDFrequency <= DesiredBandUpper) & ...
        abs(InputPSDFrequency - ...
        InputInterferenceAliasFrequency) > AliasGuardHalfWidth;
    OutputBroadbandNoiseMask = ...
        OutputPSDFrequency > DCGuardBandwidth & ...
        ~(OutputPSDFrequency >= DesiredBandLower & ...
        OutputPSDFrequency <= DesiredBandUpper) & ...
        abs(OutputPSDFrequency - ...
        OutputAliasFrequency) > AliasGuardHalfWidth;

    if ~any(InputBroadbandNoiseMask) || ...
            ~any(OutputBroadbandNoiseMask)
        error('RunDemoDecimator:EmptyNoiseMeasurementBand', ...
            ['No PSD bins remain in an input or output broadband-noise ', ...
             'measurement region.']);
    end

    InputDesiredSignalPower = sum( ...
        InputComponentMeasurements.ComponentPower_V2(1:2));
    OutputDesiredSignalPower = sum( ...
        OutputComponentMeasurements.ComponentPower_V2(1:2));
    InputBroadbandNoisePower = sum( ...
        InputPowerPSD(InputBroadbandNoiseMask)) * ...
        InputPSDSpacing;
    OutputBroadbandNoisePower = sum( ...
        OutputPowerPSD(OutputBroadbandNoiseMask)) * ...
        OutputPSDSpacing;
    InputInterferencePower = ...
        InputComponentMeasurements.ComponentPower_V2(3);
    OutputAliasPower = ...
        OutputComponentMeasurements.ComponentPower_V2(3);

    InputSNR_dB = 10 * log10( ...
        max(InputDesiredSignalPower, realmin("double")) / ...
        max(InputBroadbandNoisePower, realmin("double")));
    OutputSNR_dB = 10 * log10( ...
        max(OutputDesiredSignalPower, realmin("double")) / ...
        max(OutputBroadbandNoisePower, realmin("double")));
    InputSINR_dB = 10 * log10( ...
        max(InputDesiredSignalPower, realmin("double")) / ...
        max( ...
            InputBroadbandNoisePower + InputInterferencePower, ...
            realmin("double")));
    OutputSINR_dB = 10 * log10( ...
        max(OutputDesiredSignalPower, realmin("double")) / ...
        max( ...
            OutputBroadbandNoisePower + OutputAliasPower, ...
            realmin("double")));

    SNRImprovement_dB = OutputSNR_dB - InputSNR_dB;
    SINRImprovement_dB = OutputSINR_dB - InputSINR_dB;
    ReceivedAliasSuppression_dB = 10 * log10( ...
        max(InputInterferencePower, realmin("double")) / ...
        max(OutputAliasPower, realmin("double")));

    UpstreamSNR_dB = double( ...
        State.ADCEncoder.PowerRatios.OutputSNR_dB);
    UpstreamSINR_dB = double( ...
        State.ADCEncoder.PowerRatios.OutputSINR_dB);
    UpstreamBroadbandNoisePower = double( ...
        State.ADCEncoder.PowerRatios.OutputBroadbandNoisePower_V2);
    UpstreamComponentMeasurements = ...
        State.ADCEncoder.PowerRatios.OutputComponentMeasurements;

    RequiredComponentVariables = { ...
        'MeasuredFrequency_Hz', ...
        'ComponentPower_V2'};

    if ~istable(UpstreamComponentMeasurements) || ...
            height(UpstreamComponentMeasurements) < 3 || ...
            any(~ismember( ...
                RequiredComponentVariables, ...
                UpstreamComponentMeasurements.Properties.VariableNames))
        error('RunDemoDecimator:InvalidEncoderPowerMeasurements', ...
            ['The ADC-encoder component-power table must contain ', ...
             'Data 1, Data 2, and the ADC-rate interference alias.']);
    end

    HandoffMetricScale = max(1, max(abs([ ...
        InputSNR_dB, InputSINR_dB, ...
        UpstreamSNR_dB, UpstreamSINR_dB])));
    HandoffMetricTolerance_dB = max( ...
        1e-10, 256 * eps(HandoffMetricScale));
    HandoffPowerScale = max(1, max(abs([ ...
        InputDesiredSignalPower; ...
        InputBroadbandNoisePower; ...
        InputInterferencePower])));
    HandoffPowerTolerance = max( ...
        1e-14, 256 * eps(HandoffPowerScale));
    PowerRatioHandoffOK = ...
        abs(InputSNR_dB - UpstreamSNR_dB) <= ...
        HandoffMetricTolerance_dB && ...
        abs(InputSINR_dB - UpstreamSINR_dB) <= ...
        HandoffMetricTolerance_dB && ...
        abs(InputBroadbandNoisePower - ...
        UpstreamBroadbandNoisePower) <= ...
        HandoffPowerTolerance && ...
        all(abs( ...
            InputComponentMeasurements.MeasuredFrequency_Hz - ...
            UpstreamComponentMeasurements.MeasuredFrequency_Hz(1:3)) <= ...
            FFTGridTolerance) && ...
        all(abs( ...
            InputComponentMeasurements.ComponentPower_V2 - ...
            UpstreamComponentMeasurements.ComponentPower_V2(1:3)) <= ...
            HandoffPowerTolerance);
    SNRImprovementOK = ...
        SNRImprovement_dB >= MinimumSNRImprovement_dB;
    SINRImprovementOK = ...
        SINRImprovement_dB >= MinimumSINRImprovement_dB;

    InputNoiseMeasurementBandwidth_Hz = ...
        nnz(InputBroadbandNoiseMask) * InputPSDSpacing;
    OutputNoiseMeasurementBandwidth_Hz = ...
        nnz(OutputBroadbandNoiseMask) * OutputPSDSpacing;

    PowerRatioSummary = table( ...
