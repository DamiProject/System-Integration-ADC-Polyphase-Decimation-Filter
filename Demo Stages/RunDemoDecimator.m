function [OutputCodes, FinalMACData, Summary] = ...
        LocalProcessFixedStream( ...
        Decimator, InputCodes, FrameLength, ...
        InputFormat, CoefficientFormat, MACFormat)
%% Process one complete integer stream without padding intermediate frames.

    NumberInputSamples = numel(InputCodes);
    NumberFrames = ceil(NumberInputSamples / FrameLength);
    OutputCodes = zeros(0, 1, 'int64');
    OutputSampleIndex = zeros(0, 1);
    FinalMACData = [];
    TotalPaddingSamples = 0;

    for FrameNumber = 1:NumberFrames
        FrameStart = (FrameNumber - 1) * FrameLength + 1;
        FrameEnd = min( ...
            FrameNumber * FrameLength, NumberInputSamples);
        IsLastFrame = FrameNumber == NumberFrames;

        if isempty(MACFormat)
            [OutputFrame, FinalMACData, FrameInfo] = ...
                Decimator.ProcessFrame( ...
                    InputCodes(FrameStart:FrameEnd), ...
                    IsLastFrame, ...
                    InputFormat, ...
                    CoefficientFormat);
        else
            [OutputFrame, FinalMACData, FrameInfo] = ...
                Decimator.ProcessFrame( ...
                    InputCodes(FrameStart:FrameEnd), ...
                    IsLastFrame, ...
                    InputFormat, ...
                    CoefficientFormat, ...
                    MACFormat);
        end

        OutputCodes = [ ...
            OutputCodes; OutputFrame(:)]; %#ok<AGROW>
        OutputSampleIndex = [ ...
            OutputSampleIndex; ...
            FrameInfo.OutputSampleIndex(:)]; %#ok<AGROW>
        TotalPaddingSamples = ...
            TotalPaddingSamples + FrameInfo.NumPaddingSamples;
    end

    Summary.FramesProcessed = NumberFrames;
    Summary.TotalPaddingSamples = TotalPaddingSamples;
    Summary.OutputSampleIndex = OutputSampleIndex;
    Summary.StreamFinalized = Decimator.StreamFinalized;
end


function [OutputSignal, Summary] = ...
        LocalProcessFloatingStream( ...
        Decimator, InputSignal, FrameLength)
%% Process the matching floating-point reference using identical framing.

    NumberInputSamples = numel(InputSignal);
    NumberFrames = ceil(NumberInputSamples / FrameLength);
    OutputSignal = zeros(0, 1);
    OutputSampleIndex = zeros(0, 1);
    TotalPaddingSamples = 0;

    for FrameNumber = 1:NumberFrames
        FrameStart = (FrameNumber - 1) * FrameLength + 1;
        FrameEnd = min( ...
            FrameNumber * FrameLength, NumberInputSamples);
        IsLastFrame = FrameNumber == NumberFrames;

        [OutputFrame, FrameInfo] = ...
            Decimator.ProcessFrame( ...
                InputSignal(FrameStart:FrameEnd), ...
                IsLastFrame);

        OutputSignal = [ ...
            OutputSignal; OutputFrame(:)]; %#ok<AGROW>
        OutputSampleIndex = [ ...
            OutputSampleIndex; ...
            FrameInfo.OutputSampleIndex(:)]; %#ok<AGROW>
        TotalPaddingSamples = ...
            TotalPaddingSamples + FrameInfo.NumPaddingSamples;
    end

    Summary.FramesProcessed = NumberFrames;
    Summary.TotalPaddingSamples = TotalPaddingSamples;
    Summary.OutputSampleIndex = OutputSampleIndex;
    Summary.StreamFinalized = Decimator.StreamFinalized;
end


function BranchTapCounts = ...
        LocalBranchTapCounts(FilterLength, DecimationFactor)
%% Return the number of real prototype coefficients in each branch.

    PhaseIndex = 0:DecimationFactor - 1;
    BranchTapCounts = max( ...
        0, ...
        floor((FilterLength - 1 - PhaseIndex) / ...
        DecimationFactor) + 1);
end


function [MeasuredFrequency, PeakMagnitude] = ...
        LocalMeasureFFTPeaks( ...
        Frequency, Magnitude, TargetFrequencies, SearchHalfWidth)
%% Measure the strongest Hamming-FFT bin in each local tone-search band.

    Frequency = Frequency(:);
    Magnitude = Magnitude(:);
    TargetFrequencies = TargetFrequencies(:);

    if numel(Frequency) ~= numel(Magnitude)
        error('RunDemoDecimator:FFTLengthMismatch', ...
            'FFT frequency and magnitude vectors must have equal lengths.');
    end

    MeasuredFrequency = zeros(size(TargetFrequencies));
    PeakMagnitude = zeros(size(TargetFrequencies));

    for k = 1:numel(TargetFrequencies)
        SearchMask = abs( ...
            Frequency - TargetFrequencies(k)) <= SearchHalfWidth;

        if ~any(SearchMask)
            error('RunDemoDecimator:EmptyToneSearchBand', ...
                ['No Hamming-FFT bins lie inside a desired-tone ', ...
                 'search band.']);
        end

        CandidateIndices = find(SearchMask);
        [PeakMagnitude(k), LocalPeakIndex] = ...
            max(Magnitude(SearchMask));
        MeasuredFrequency(k) = ...
            Frequency(CandidateIndices(LocalPeakIndex));
    end
end


function AliasFrequency = LocalFoldToFirstNyquist( ...
        InputFrequency, SamplingFrequency)
%% Fold a nonnegative frequency into the real-signal first Nyquist zone.

    AliasFrequency = abs(mod( ...
        InputFrequency + SamplingFrequency / 2, ...
        SamplingFrequency) - SamplingFrequency / 2);
end


function [PSDFrequency, PowerPSD] = LocalHammingPSD( ...
        InputSignal, SamplingFrequency, ...
        WindowLength, OverlapLength, FFTLength)
%% Hamming-Welch PSD using decimator-specific matched-time lengths.

    InputSignal = InputSignal(:);

    if numel(InputSignal) < WindowLength
        error('RunDemoDecimator:PSDRecordTooShort', ...
            'The signal is shorter than its Hamming-Welch window.');
    end

    if OverlapLength >= WindowLength
        error('RunDemoDecimator:InvalidPSDOverlap', ...
            'PSD overlap must be shorter than its Welch window.');
    end

    if FFTLength < WindowLength
        error('RunDemoDecimator:InvalidPSDFFTLength', ...
            'PSD FFT length must be at least the Welch window length.');
    end

    HammingWindow = hamming(WindowLength, "periodic");
    [PowerPSD, PSDFrequency] = pwelch( ...
        InputSignal, ...
        HammingWindow, ...
        OverlapLength, ...
        FFTLength, ...
        SamplingFrequency, ...
        "onesided");
end


function Result = LocalPassFail(Condition)
%% Convert a scalar compliance decision to a readable label.

    if Condition
        Result = "PASS";
    else
        Result = "FAIL";
    end
